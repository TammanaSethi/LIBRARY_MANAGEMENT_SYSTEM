if ($_SERVER["REQUEST_METHOD"] == "POST") {
    $username = mysqli_real_escape_string($conn, $_POST['username']);
    $email = mysqli_real_escape_string($conn, $_POST['email']);
    $password = password_hash($_POST['password'], PASSWORD_DEFAULT);
    $role = mysqli_real_escape_string($conn, $_POST['role']);
    $first_name = mysqli_real_escape_string($conn, $_POST['first_name']);
    $last_name = mysqli_real_escape_string($conn, $_POST['last_name']);
    
    // Check if username already exists
    $check_sql = "SELECT id FROM users WHERE username = ? OR email = ?";
    $check_stmt = mysqli_prepare($conn, $check_sql);
    mysqli_stmt_bind_param($check_stmt, "ss", $username, $email);
    mysqli_stmt_execute($check_stmt);
    mysqli_stmt_store_result($check_stmt);
    
    if (mysqli_stmt_num_rows($check_stmt) > 0) {
        $error = "Username or email already exists!";
    } else {
        $can_register = true;
        
        if ($can_register) {
            // Start transaction
            mysqli_begin_transaction($conn);
            
            try {
                // Insert user
                $status = ($role == 'teacher') ? 'approved' : 'pending';
                $sql = "INSERT INTO users (username, email, password, role, first_name, last_name, status) VALUES (?, ?, ?, ?, ?, ?, ?)";
                $stmt = mysqli_prepare($conn, $sql);
                mysqli_stmt_bind_param($stmt, "sssssss", $username, $email, $password, $role, $first_name, $last_name, $status);
                mysqli_stmt_execute($stmt);
                $user_id = mysqli_insert_id($conn);
                
                mysqli_commit($conn);
                $success = "Registration successful! ";
                $success .= ($role == 'student') ? "Please wait for teacher approval." : "You can now login.";
                header("refresh:3;url=login.php");
            } catch (Exception $e) {
                mysqli_rollback($conn);
                $error = "Error during registration. Please try again.";
            }
        }
    }
}
